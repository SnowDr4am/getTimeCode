"""Приведение ответа LLM к главам YouTube."""

import timecodes

# Ответ модели на старый промпт — ровно тот мусор, который надо вычищать.
MESSY = """**Вот кликбейтные тайм-коды для видео:**

[00:00:05] 🔥 Как вызывать доверие девушки за 30 секунд
[00:01:38] 🚨 Мозг не отличает реальность от фантазии!
[01:03:16] ⚡️ 4 паттерна, которые ломают шаблон

Можешь копировать и использовать в описании видео. Хочешь более жёсткие варианты — скажи."""


def test_запрос_знает_длину_и_число_тайм_кодов():
    prompt = timecodes.request("[00:00:00] Привет.", 7206)
    assert prompt.startswith("Длительность эфира: 02:00:06. Нужно 30–48 тайм-кодов")
    assert prompt.endswith("Расшифровка:\n[00:00:00] Привет.")


def test_короткому_эфиру_минимум_три_главы():
    assert "Нужно 3 тайм-кодов" in timecodes.request("", 60)


def test_мусорный_ответ_становится_главами():
    assert timecodes.normalize(MESSY, []) == (
        "00:00 — Как вызывать доверие девушки за 30 секунд\n"
        "01:38 — Мозг не отличает реальность от фантазии!\n"
        "01:03:16 — 4 паттерна, которые ломают шаблон"
    )


def test_правильный_ответ_не_меняется():
    good = ("00:00 — Почему ты БОИШЬСЯ знакомиться\n"
            "03:23 — Тебя учили быть «удобным»?\n"
            "01:04:56 — У тебя НЕ БУДЕТ второй попытки")
    assert timecodes.normalize(good, []) == good


def test_разные_разделители_и_маркеры_списка():
    answer = "1. 00:00 - Старт\n- **05:10** | Середина\n• 10:20: Финал"
    assert timecodes.normalize(answer, []) == "00:00 — Старт\n05:10 — Середина\n10:20 — Финал"


def test_порядок_и_дубли_времени():
    answer = "10:00 — Б\n00:00 — А\n10:00 — повтор"
    assert timecodes.normalize(answer, []) == "00:00 — А\n10:00 — Б"


def test_первая_глава_всегда_с_нуля():
    answer = timecodes.normalize("00:12 — Вступление\n03:00 — Суть", [])
    assert answer.startswith("00:00 — Вступление")


def test_время_внутри_фразы_не_тайм_код():
    answer = "Эфир начинается в 12:30 по Москве\n00:00 — Старт"
    assert timecodes.normalize(answer, []) == "00:00 — Старт"


def test_невалидное_время_пропускается():
    answer = timecodes.normalize("00:00 — А\n05:75 — битое\n07:00 — Б", [])
    assert answer == "00:00 — А\n07:00 — Б"


def test_без_тайм_кодов_ответ_как_есть():
    assert timecodes.normalize("  Не могу помочь с этим.  ", []) == "Не могу помочь с этим."


def test_кавычки_и_капс_сохраняются():
    assert timecodes.normalize("00:00 — «Я НЕ знакомлюсь» 😅", []) == "00:00 — «Я НЕ знакомлюсь»"


def test_время_привязывается_к_началу_блока():
    """Модель округлила или выдумала время — берём ближайшую реальную метку расшифровки."""
    answer = "00:00 — А\n03:00 — Б\n03:10 — дубль после привязки\n59:59 — В"
    marks = [0.0, 95.2, 187.6, 3610.0]
    assert timecodes.normalize(answer, marks) == "00:00 — А\n03:07 — Б\n01:00:10 — В"


def test_метки_расшифровки_в_формате_ответа():
    blocks = [{"start": 0, "end": 30, "text": "Привет."},
              {"start": 203.4, "end": 260, "text": "Тема."},
              {"start": 3725.4, "end": 3800, "text": "Итог."}]
    assert timecodes.render_transcript(blocks) == (
        "[00:00] Привет.\n[03:23] Тема.\n[01:02:05] Итог.")
