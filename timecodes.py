# Плотность глав, секунд эфира на тайм-код: реже — теряются темы, чаще — описание
# превращается в оглавление. Диапазон, а не число: точное число модель раскладывает сеткой.
DENSE_SEC, SPARSE_SEC = 150, 240
MIN_TIMECODES = 3  # меньше трёх глав YouTube не показывает


def fmt(seconds: float) -> str:
    h, rest = divmod(int(seconds), 3600)
    m, s = divmod(rest, 60)
    return f"{h:02d}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def render_transcript(blocks: list[dict]) -> str:
    """Метки в том же формате, что и ответ: модель копирует их, а не пересчитывает — при
    [ЧЧ:ММ:СС] на входе она путала часы с минутами."""
    return "\n".join(f"[{fmt(b['start'])}] {b['text']}" for b in blocks)


def request(transcript: str, duration: float) -> str:
    """Длина эфира и нужное число тайм-кодов прямо в запросе: без них модель выдыхается
    на первом часе и бросает остаток эфира."""
    low = max(MIN_TIMECODES, round(duration / SPARSE_SEC))
    high = max(low, round(duration / DENSE_SEC))
    count = f"{low}–{high}" if high > low else str(low)
    return (f"Длительность эфира: {fmt(duration)}. Нужно {count} тайм-кодов, "
            f"последний — в последние 10 минут эфира.\n\nРасшифровка:\n{transcript}")
